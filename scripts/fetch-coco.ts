/**
 * Prefetch Coco Material illustrations (CC0 hand-drawn SVGs) for the "figure
 * doing an activity" scenes (Rule #2). Saves them into a bundled TS module so
 * the render is deterministic and offline — no network inside a frame.
 *
 * Each key tries a list of candidate tags until one returns an SVG.
 * Usage: npm run fetch-coco
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "src", "generated", "coco.ts");

// key -> candidate Coco Material tags (first that yields an SVG wins)
const WANT: Record<string, string[]> = {
  child: ["child", "kid", "boy", "girl"],
  confused: ["confused", "doubt", "question", "thinking"],
  argument: ["argument", "angry", "fight", "discussion", "conflict"],
  brain: ["brain", "mind", "head"],
  reunion: ["hug", "love", "friends", "couple"],
  music: ["music", "headphones", "listen", "song"],
  mountain: ["mountain", "landscape", "nature"],
  writing: ["writing", "write", "notebook", "journal", "studying"],
  waiting: ["waiting", "clock", "time", "wait"],
  nature: ["flower", "plant", "nature", "leaf"],
  climbing: ["climbing", "climb", "mountain", "strength"],
  heart: ["heart", "love", "like"],
};

async function fetchTag(tag: string): Promise<string | null> {
  try {
    const res = await fetch(`https://cocomaterial.com/api/vectors/?tags=${encodeURIComponent(tag)}`, {
      headers: { "User-Agent": "Mozilla/5.0 (coco-prefetch)" },
    });
    if (!res.ok) return null;
    const data = (await res.json()) as { results?: { coloredSvgContent?: string; svgContent?: string }[] };
    for (const r of data.results ?? []) {
      const svg = r.coloredSvgContent || r.svgContent;
      if (svg && svg.includes("<svg")) return svg;
    }
    return null;
  } catch {
    return null;
  }
}

async function main() {
  const out: Record<string, string> = {};
  for (const [key, tags] of Object.entries(WANT)) {
    let got: string | null = null;
    let used = "";
    for (const tag of tags) {
      got = await fetchTag(tag);
      if (got) {
        used = tag;
        break;
      }
    }
    if (got) {
      out[key] = got;
      console.log(`✓ ${key.padEnd(10)} <- "${used}"`);
    } else {
      console.log(`✗ ${key.padEnd(10)} (no illustration found; scene falls back gracefully)`);
    }
  }

  mkdirSync(dirname(OUT), { recursive: true });
  const body =
    "// AUTO-GENERATED by scripts/fetch-coco.ts — Coco Material illustrations (CC0).\n" +
    "// Do not edit by hand. Run `npm run fetch-coco` to refresh.\n" +
    "export const COCO: Record<string, string> = " +
    JSON.stringify(out, null, 2) +
    ";\n";
  writeFileSync(OUT, body);
  console.log(`\nWrote ${Object.keys(out).length} illustrations -> src/generated/coco.ts`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
